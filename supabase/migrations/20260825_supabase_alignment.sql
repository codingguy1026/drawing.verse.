-- Keep posts.comment_count authoritative in the database.
create or replace function public.sync_post_comment_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_id bigint;
begin
  target_id := case when tg_op = 'DELETE' then old.post_id else new.post_id end;

  update public.posts
  set comment_count = (
    select count(*)::integer
    from public.comments
    where post_id = target_id
  )
  where id = target_id;

  if tg_op = 'UPDATE' and old.post_id is distinct from new.post_id then
    update public.posts
    set comment_count = (
      select count(*)::integer
      from public.comments
      where post_id = old.post_id
    )
    where id = old.post_id;
  end if;

  return null;
end;
$$;

drop trigger if exists comments_sync_post_count on public.comments;
create trigger comments_sync_post_count
after insert or delete or update of post_id on public.comments
for each row execute function public.sync_post_comment_count();

