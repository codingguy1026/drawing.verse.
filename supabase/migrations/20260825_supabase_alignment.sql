update public.posts p
set comment_count = (
  select count(*)::integer from public.comments c where c.post_id = p.id
);

update public.posts p
set like_count = (
  select count(*)::integer from public.post_stars s where s.post_id = p.id
);

update public.universes u
set post_count = (
  select count(*)::integer from public.posts p where p.universe_slug = u.slug
),
subscriber_count = (
  select count(*)::integer from public.universe_subscriptions s where s.universe_slug = u.slug
);

update public.profiles p
set universes_count = (
  select count(*)::integer from public.universes u where u.owner_id = p.id
);
