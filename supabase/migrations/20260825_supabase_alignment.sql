create or replace function public.match_verse_talk(display_nickname text)
returns setof public.verse_talk_rooms
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  clean_nickname text := left(trim(display_nickname), 30);
  opponent public.verse_talk_queue%rowtype;
  existing_room public.verse_talk_rooms%rowtype;
  created_room public.verse_talk_rooms%rowtype;
begin
  if me is null then
    raise exception 'authentication required';
  end if;

  if clean_nickname is null or clean_nickname = '' then
    raise exception 'nickname required';
  end if;

  select * into existing_room
  from public.verse_talk_rooms
  where status = 'active' and (user_a = me or user_b = me)
  order by created_at desc
  limit 1;

  if found then
    return next existing_room;
    return;
  end if;

  delete from public.verse_talk_queue where user_id = me;

  select * into opponent
  from public.verse_talk_queue
  where user_id <> me
  order by created_at asc
  for update skip locked
  limit 1;

  if found then
    delete from public.verse_talk_queue where id = opponent.id;

    insert into public.verse_talk_rooms(
      user_a, user_b, user_a_nickname, user_b_nickname, status
    ) values (
      me, opponent.user_id, clean_nickname, opponent.nickname, 'active'
    )
    returning * into created_room;

    return next created_room;
    return;
  end if;

  insert into public.verse_talk_queue(user_id, nickname)
  values (me, clean_nickname)
  on conflict (user_id)
  do update set nickname = excluded.nickname, created_at = now();

  return;
end;
$$;

grant execute on function public.match_verse_talk(text) to authenticated;

